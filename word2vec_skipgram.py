"""
word2vec_skipgram.py
Συνοδευτικό πρόγραμμα του Κεφαλαίου 6 (LLM in a Nutshell).

Ένα μικροσκοπικό Word2Vec (αρχιτεκτονική Skip-gram με αρνητική δειγματοληψία)
σε καθαρό numpy, χωρίς εξωτερικά πακέτα πέρα από το numpy.

Τι κάνει:
  1. Φτιάχνει ζεύγη συνύπαρξης (κεντρική λέξη, λέξη του περιβάλλοντος).
  2. Εκπαιδεύει διανύσματα ενσωμάτωσης (embeddings) με «έλξη» και «άπωση».
  3. Δοκιμάζει τις διανυσματικές αναλογίες του κεφαλαίου
     (βασιλιάς − άνδρας + γυναίκα ≈ βασίλισσα) με συνημιτονική ομοιότητα.

Σημείωση: το σώμα κειμένων είναι εκπαιδευτικό και σκόπιμα επαναλαμβανόμενο.
Σε αληθινό κείμενο τα αποτελέσματα είναι πολύ λιγότερο καθαρά.

Εκτέλεση:   python3 word2vec_skipgram.py
"""
import numpy as np

# ==============================================================================
# 1. ΡΥΘΜΙΣΕΙΣ
# ==============================================================================
WINDOW = 5          # πέντε λέξεις εκατέρωθεν της κεντρικής λέξης
DIM = 32            # διάσταση των διανυσμάτων ενσωμάτωσης (d)
NEGATIVES = 5       # πόσα «αρνητικά» δείγματα (άπωση) ανά πραγματικό ζεύγος
EPOCHS = 200        # πόσες εποχές (πλήρη περάσματα από όλα τα ζεύγη)
LEARNING_RATE = 0.05
SEED = 0
SUBSAMPLING_T = None   # π.χ. 0.02 για να ενεργοποιηθεί το subsampling (None = κλειστό)

# ==============================================================================
# 2. ΤΟ ΣΩΜΑ ΚΕΙΜΕΝΩΝ (corpus)
# ==============================================================================
CORPUS = """
Η γάτα κάθισε στο χαλάκι.
Το γατάκι είναι ένα μωρό γάτας.
Ο βασιλιάς είναι ένας άνδρας που κυβερνά το βασίλειο.
Η βασίλισσα είναι μια γυναίκα που κυβερνά το βασίλειο.
Ο πρίγκιπας είναι ένας νεαρός άνδρας βασιλικής καταγωγής.
Η πριγκίπισσα είναι μια νεαρή γυναίκα βασιλικής καταγωγής.
Ο βασιλιάς ζει στο παλάτι.
Ο βασιλιάς αγαπά την οικογένειά του.
Ο βασιλιάς περπατά με τον φίλο του.
Ο βασιλιάς είναι ένας άνδρας.
Ο βασιλιάς μιλά με τον γείτονά του.
Ο βασιλιάς πηγαίνει στο σπίτι του.
Ο βασιλιάς κυβερνά το βασίλειό του.
Η βασίλισσα ζει στο παλάτι.
Η βασίλισσα αγαπά την οικογένειά της.
Η βασίλισσα περπατά με τον φίλο της.
Η βασίλισσα είναι μια γυναίκα.
Η βασίλισσα μιλά με τον γείτονά της.
Η βασίλισσα πηγαίνει στο σπίτι της.
Η βασίλισσα κυβερνά το βασίλειό της.
Ο πρίγκιπας ζει στο παλάτι.
Ο πρίγκιπας αγαπά την οικογένειά του.
Ο πρίγκιπας περπατά με τον φίλο του.
Ο πρίγκιπας είναι ένας νεαρός άνδρας.
Ο πρίγκιπας μιλά με τον γείτονά του.
Ο πρίγκιπας πηγαίνει στο σπίτι του.
Η πριγκίπισσα ζει στο παλάτι.
Η πριγκίπισσα αγαπά την οικογένειά της.
Η πριγκίπισσα περπατά με τον φίλο της.
Η πριγκίπισσα είναι μια νεαρή γυναίκα.
Η πριγκίπισσα μιλά με τον γείτονά της.
Η πριγκίπισσα πηγαίνει στο σπίτι της.
Ο άνδρας ζει στο χωριό.
Ο άνδρας αγαπά την οικογένειά του.
Ο άνδρας περπατά με τον φίλο του.
Ο άνδρας είναι ένας άνθρωπος.
Ο άνδρας μιλά με τον γείτονά του.
Ο άνδρας πηγαίνει στο σπίτι του.
Η γυναίκα ζει στο χωριό.
Η γυναίκα αγαπά την οικογένειά της.
Η γυναίκα περπατά με τον φίλο της.
Η γυναίκα είναι ένας άνθρωπος.
Η γυναίκα μιλά με τον γείτονά της.
Η γυναίκα πηγαίνει στο σπίτι της.
Το αγόρι ζει στο χωριό.
Το αγόρι αγαπά την οικογένειά του.
Το αγόρι περπατά με τον φίλο του.
Το αγόρι είναι ένας νεαρός άνδρας.
Το αγόρι μιλά με τον γείτονά του.
Το αγόρι πηγαίνει στο σπίτι του.
Το κορίτσι ζει στο χωριό.
Το κορίτσι αγαπά την οικογένειά της.
Το κορίτσι περπατά με τον φίλο της.
Το κορίτσι είναι μια νεαρή γυναίκα.
Το κορίτσι μιλά με τον γείτονά της.
Το κορίτσι πηγαίνει στο σπίτι της.
"""

# Κάθε πρόταση γίνεται λίστα λέξεων: πεζά γράμματα, χωρίς σημεία στίξης.
sentences = [
    line.lower().replace(".", "").split()
    for line in CORPUS.strip().splitlines()
]
n_words = sum(len(s) for s in sentences)

vocab = sorted({w for s in sentences for w in s})
word_to_id = {w: i for i, w in enumerate(vocab)}
V = len(vocab)

print(f"Προτάσεις: {len(sentences)} | Λέξεις: {n_words} | Λεξιλόγιο: {V} λέξεις")

# ==============================================================================
# 3. ΔΗΜΙΟΥΡΓΙΑ ΖΕΥΓΩΝ ΣΥΝΥΠΑΡΞΗΣ
# ==============================================================================
rng = np.random.default_rng(SEED)

# Σχετική συχνότητα κάθε λέξης (για το subsampling και την αρνητική δειγματοληψία)
counts = np.zeros(V)
for s in sentences:
    for w in s:
        counts[word_to_id[w]] += 1
freq = counts / counts.sum()


def keep(word_id):
    """Subsampling του Mikolov: P(απόρριψη) = 1 - sqrt(t / f(w))."""
    if SUBSAMPLING_T is None:
        return True
    p_discard = max(0.0, 1 - np.sqrt(SUBSAMPLING_T / freq[word_id]))
    return rng.random() >= p_discard


pairs = []
for s in sentences:
    ids = [word_to_id[w] for w in s]
    for i, center in enumerate(ids):
        if not keep(center):
            continue
        lo, hi = max(0, i - WINDOW), min(len(ids), i + WINDOW + 1)
        for j in range(lo, hi):
            if j != i and keep(ids[j]):
                pairs.append((center, ids[j]))
pairs = np.array(pairs)
print(f"Παράθυρο: {WINDOW} εκατέρωθεν | Ζεύγη εκπαίδευσης: {len(pairs)} "
      f"({len(pairs) / n_words:.1f} ανά λέξη)")

# ==============================================================================
# 4. ΕΚΠΑΙΔΕΥΣΗ: ΕΛΞΗ ΚΑΙ ΑΠΩΣΗ
# ==============================================================================
# Δύο πίνακες V × d:
#   W : τα διανύσματα ενσωμάτωσης (αυτά κρατάμε στο τέλος)
#   C : βοηθητικοί πίνακες «περιβάλλοντος», που χρησιμοποιούνται μόνο στην εκπαίδευση
W = (rng.random((V, DIM)) - 0.5) / DIM
C = np.zeros((V, DIM))

# Οι «αρνητικές» λέξεις επιλέγονται με πιθανότητα ανάλογη της συχνότητας^0,75
neg_prob = freq ** 0.75
neg_prob /= neg_prob.sum()


def sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


print(f"\nΕκπαίδευση για {EPOCHS} εποχές...")
for epoch in range(EPOCHS):
    order = rng.permutation(len(pairs))
    negatives = rng.choice(V, size=(len(pairs), NEGATIVES), p=neg_prob)
    for k in order:
        center, context = pairs[k]
        w = W[center]

        # Έλξη: το πραγματικό ζεύγος πρέπει να έχει υψηλή ομοιότητα (στόχος: 1)
        g = sigmoid(w @ C[context]) - 1.0
        grad_w = g * C[context]
        C[context] -= LEARNING_RATE * g * w

        # Άπωση: τυχαίες λέξεις πρέπει να έχουν χαμηλή ομοιότητα (στόχος: 0)
        for neg in negatives[k]:
            if neg == context:
                continue
            g = sigmoid(w @ C[neg])
            grad_w += g * C[neg]
            C[neg] -= LEARNING_RATE * g * w

        W[center] -= LEARNING_RATE * grad_w

# ==============================================================================
# 5. ΜΕΤΡΗΣΗ ΟΜΟΙΟΤΗΤΑΣ ΚΑΙ ΔΙΑΝΥΣΜΑΤΙΚΗ ΑΡΙΘΜΗΤΙΚΗ
# ==============================================================================
def cosine(a, b):
    return float(a @ b / (np.linalg.norm(a) * np.linalg.norm(b)))


def closest(vector, exclude, k=3):
    """Οι k λέξεις με τη μεγαλύτερη συνημιτονική ομοιότητα προς το διάνυσμα."""
    scores = [(w, cosine(vector, W[word_to_id[w]])) for w in vocab if w not in exclude]
    return sorted(scores, key=lambda x: -x[1])[:k]


print("\n--- Συνημιτονική ομοιότητα ---")
for a, b in [("βασιλιάς", "βασίλισσα"), ("άνδρας", "γυναίκα"), ("βασιλιάς", "γάτα")]:
    print(f"cos({a}, {b}) = {cosine(W[word_to_id[a]], W[word_to_id[b]]):+.2f}")

print("\n--- Διανυσματικές αναλογίες ---")
analogies = [
    ("βασιλιάς", "άνδρας", "γυναίκα"),      # αναμένεται: βασίλισσα
    ("βασίλισσα", "γυναίκα", "άνδρας"),     # αναμένεται: βασιλιάς
    ("πρίγκιπας", "αγόρι", "κορίτσι"),      # αναμένεται: πριγκίπισσα
]
for a, b, c in analogies:
    v = W[word_to_id[a]] - W[word_to_id[b]] + W[word_to_id[c]]
    top = closest(v, exclude={a, b, c})
    best = ", ".join(f"{w} ({s:+.2f})" for w, s in top)
    print(f"{a} − {b} + {c}  →  {best}")
